"""Precompute local BlurHashes. Requires Pillow; never runs in the app.

Run `python scripts/generate-image-placeholders.py`, or append --check in CI.
Transparent artwork is composited on the app's white background for the hash.
"""

import argparse
import hashlib
import math
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/data/local-image-placeholders.ts"
ASSETS = sorted(
    [*ROOT.glob("assets/images/catalog/*"),
     *ROOT.glob("assets/images/onboarding/*.png"),
     *ROOT.glob("assets/images/auth/*.webp"),
     ROOT / "assets/branding/cemydi-logo-horizontal.png"]
)
BASE83 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz#$%*+,-.:;=?@[]^_{|}~"


def encode83(value, length):
    return "".join(BASE83[(value // (83 ** digit)) % 83] for digit in reversed(range(length)))


def linear(value):
    value /= 255
    return value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4


def srgb(value):
    value = min(1, max(0, value))
    value = value * 12.92 if value <= 0.0031308 else 1.055 * value ** (1 / 2.4) - 0.055
    return int(value * 255 + 0.5)


def blurhash(path):
    with Image.open(path) as original:
        rgba = original.convert("RGBA")
        image = Image.alpha_composite(Image.new("RGBA", rgba.size, "white"), rgba).convert("RGB")
    image.thumbnail((32, 32), Image.Resampling.LANCZOS)
    width, height = image.size
    pixels = [tuple(linear(channel) for channel in image.getpixel((x, y)))
              for y in range(height) for x in range(width)]
    factors = []
    for cy in range(3):
        for cx in range(4):
            total = [0.0, 0.0, 0.0]
            for y in range(height):
                for x in range(width):
                    basis = math.cos(math.pi * cx * x / width) * math.cos(math.pi * cy * y / height)
                    for channel in range(3):
                        total[channel] += basis * pixels[y * width + x][channel]
            scale = (1 if cx == cy == 0 else 2) / (width * height)
            factors.append([value * scale for value in total])
    maximum = max(abs(value) for factor in factors[1:] for value in factor)
    quantized_max = min(82, max(0, math.floor(maximum * 166 - 0.5)))
    maximum = (quantized_max + 1) / 166
    dc = [srgb(value) for value in factors[0]]
    result = encode83(3 + 2 * 9, 1) + encode83(quantized_max, 1)
    result += encode83((dc[0] << 16) + (dc[1] << 8) + dc[2], 4)
    for factor in factors[1:]:
        quantized = [
            min(18, max(0, math.floor(math.copysign(math.sqrt(abs(value / maximum)), value) * 9 + 9.5)))
            for value in factor
        ]
        result += encode83(quantized[0] * 19 * 19 + quantized[1] * 19 + quantized[2], 2)
    assert len(result) == 28 and all(char in BASE83 for char in result)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lines = [
        "// Generated by scripts/generate-image-placeholders.py; do not edit hashes by hand.",
        "import type { ImageSourcePropType } from 'react-native';",
        "",
        "const localImageBlurhashes = new Map<ImageSourcePropType, string>([",
    ]
    for asset in ASSETS:
        name = asset.relative_to(ROOT).as_posix()
        digest = hashlib.sha256(asset.read_bytes()).hexdigest()
        hash_value = blurhash(asset)
        entry = f"  [require('../../{name}'), '{hash_value}'],"
        lines.append(f"  // SHA-256: {digest}")
        if len(entry) <= 100:
            lines.append(entry)
        else:
            lines.extend(["  [", f"    require('../../{name}'),", f"    '{hash_value}',", "  ],"])
    lines.extend([
        "]);", "",
        "export function getLocalImageBlurhash(source: ImageSourcePropType): string | undefined {",
        "  return localImageBlurhashes.get(source);",
        "}", "",
    ])
    content = "\n".join(lines)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Local placeholders are outdated. Run the generator.")
        print(f"Verified {len(ASSETS)} local image placeholders.")
    else:
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")
        print(f"Generated {len(ASSETS)} local image placeholders.")


if __name__ == "__main__":
    main()
